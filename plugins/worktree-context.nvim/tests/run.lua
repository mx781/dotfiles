-- Run with: nvim --headless -u NONE -l plugins/worktree-context.nvim/tests/run.lua
vim.opt.rtp:prepend(vim.fn.getcwd() .. '/plugins/worktree-context.nvim')
local plugin = require('worktree-context')
local tmp = vim.fn.tempname() .. ' worktrees'
vim.fn.mkdir(tmp, 'p')
local main, linked = tmp .. '/main', tmp .. '/linked tree'
local function run(argv)
  local result = vim.system(argv, { text = true }):wait()
  assert(result.code == 0, result.stderr)
end
local function git(...)
  run(vim.list_extend({ 'git', '-C', main }, { ... }))
end
local ok, err = xpcall(function()
  run({ 'git', 'init', '-q', '-b', 'master', main })
  vim.fn.mkdir(main .. '/src', 'p')
  vim.fn.writefile({ 'original' }, main .. '/src/file.txt')
  git('add', '.')
  git('-c', 'user.name=Test', '-c', 'user.email=test@example.invalid', 'commit', '-qm', 'initial')
  git('worktree', 'add', '-qb', 'feature', linked)
  vim.cmd.cd(vim.fn.fnameescape(main))
  vim.cmd.edit(vim.fn.fnameescape(main .. '/src/file.txt'))
  local buffer = vim.api.nvim_get_current_buf()
  vim.api.nvim_buf_set_lines(buffer, 0, -1, false, { 'unsaved edit' })
  vim.g.mapleader = ' '
  vim.keymap.set('n', '<leader>ww', ':echo "original"<CR>')
  local old_map = vim.fn.maparg('<leader>ww', 'n')
  local old_status = vim.o.statusline
  plugin.setup({ nerdtree = false, state_dir = tmp .. '/state' })
  local trees = assert(plugin.list())
  assert(#trees == 2 and trees[2].branch == 'refs/heads/feature')
  assert(plugin.switch(linked))
  assert(vim.fn.getcwd() == linked)
  assert(vim.api.nvim_get_current_buf() == buffer, 'Switch replaced current buffer')
  assert(vim.bo[buffer].buflisted and vim.bo[buffer].modified, 'Switch hid or saved buffer')
  assert(plugin.relative_path() == 'src/file.txt')
  assert(plugin.file_context().root == main, 'File context followed cwd')
  assert(plugin.statusline():find('feature', 1, true))
  assert(vim.api.nvim_eval_statusline(vim.o.statusline, {}).str:find('feature', 1, true))
  vim.cmd.vsplit(vim.fn.fnameescape(linked .. '/src/file.txt'))
  local second = vim.api.nvim_get_current_buf()
  assert(plugin.file_context().root == linked)
  assert(plugin.toggle() and vim.fn.getcwd() == main)
  assert(vim.api.nvim_get_current_buf() == second)
  assert(vim.bo[buffer].modified and vim.bo[second].buflisted)
  assert(plugin.toggle() and vim.fn.getcwd() == linked)
  -- Discovery must refresh after external Git operations, including detached trees.
  git('worktree', 'add', '--detach', tmp .. '/detached', 'HEAD')
  local refreshed = assert(plugin.list())
  assert(#refreshed == 3 and #vim.tbl_filter(function(tree) return tree.detached end, refreshed) == 1)
  assert(not plugin.switch(tmp), 'Accepted non-worktree directory')
  assert(vim.fn.getcwd() == linked)
  local captured
  package.loaded['fzf-lua'] = { live_grep = function(opts) captured = opts end }
  plugin.grep_all()
  assert(#captured.search_paths == 3)
  plugin.disable()
  assert(vim.fn.maparg('<leader>ww', 'n') == old_map, 'Did not restore mapping')
  assert(vim.o.statusline == old_status, 'Did not restore statusline')
  assert(vim.fn.exists(':WorktreeSwitch') == 0)
  plugin.setup({ mappings = false, statusline = false, nerdtree = false, state_dir = tmp .. '/state' })
  assert(vim.fn.maparg('<leader>ww', 'n') == old_map)
  plugin.disable()
  print('PASS: discovery, switching, dirty global buffers, file roots, toggle, search scope, disable')
end, debug.traceback)
vim.cmd.cd('/tmp')
vim.fn.delete(tmp, 'rf')
if not ok then io.stderr:write(err .. '\n'); vim.cmd('cquit 1') end
vim.cmd('qa!')
